from ranking import *
w=World()
w.add_class('Base'); w.add_class('Derived',bases=['Base'])
w.add_class('Text',ctors=[Fn('Text(const char*)',[ptr(fund('char',{'const'}))])])
I=fund('int'); L=fund('long')
def r(c,a,**k): return resolve(w,c,a,**k)
show1,show2,show3=Fn('show(long)',[L]),Fn('show(Text)',[cls('Text')]),Fn('show(...)',[],ellipsis=True)
print('show(5) ->',r([show1,show2,show3],[pr(I)]), 'want 1')
print('show("hi") ->',r([show1,show2,show3],[strlit(2)]), 'want 2')
p4,p5=Fn('put(int&)',[lref(I)]),Fn('put(const int&)',[lref(fund('int',{'const'}))])
print(r([p4,p5],[lv(I)]),'want 4'); print(r([p4,p5],[pr(I)]),'want 5'); print(r([p4,p5],[braced(lv(I))]),'want 4')
t6,t7=Fn('take(Base*)',[ptr(cls('Base'))]),Fn('take(void*)',[ptr(VOID)])
print(r([t6,t7],[pr(ptr(cls('Derived')))]),'want 6')
s8,s9=Fn('sum(il<long>)',[ilist(L)]),Fn('sum(int)',[I])
print(r([s8,s9],[braced(pr(I))]),'want 8')
w.add_enum('Level',underlying='short')
p10,p11=Fn('pick(const short&)',[lref(fund('short',{'const'}))]),Fn('pick(int&&)',[rref(I)])
print(r([p10,p11],[pr(enum('Level'))]),'want 10')
w.add_class('Pair',ctors=[Fn('Pair(int,int)',[I,I])])
w.add_class('Point',aggregate=True,fields=[('x',I),('y',I)])
w.add_class('Holder',aggregate=True,fields=[('p',cls('Point'))])
h12,h13=Fn('hold(Pair)',[cls('Pair')]),Fn('hold(Holder)',[cls('Holder')])
print(r([h12,h13],[braced(braced(pr(I),pr(I)))]),'want 13')
w.add_class('Target',ctors=[Fn('Target()',[]),Fn('Target(Source&)',[lref(cls('Source'))])])
w.add_class('Source',convs=[Fn('operator Target',[],ret=cls('Target'))])
s14,s15=Fn('send(Target)',[cls('Target')]),Fn('send(...)',[],ellipsis=True)
res=r([s14,s15],[lv(cls('Source'))]); print(res,'want 14 (with ambiguous seq)', res.viable[0].seqs if res.viable else '')
# OVL examples
sh1,sh2,sh3=Fn('show(int)',[I]),Fn('show(long)',[L]),Fn('show<T>',[I],template=True)
print(r([sh1,sh2,sh3],[pr(I)]),'want show(int)')
sh3c=Fn('show<char>',[fund('char')],template=True); sh3l=Fn('show<long>',[L],template=True)
print(r([sh1,sh2,sh3l],[pr(L)]),'want show(long)')
print(r([sh1,sh2,sh3c],[pr(fund('char'))]),'want template')
t1,t2=Fn('tick(int,long)',[I,L]),Fn('tick(long,int)',[L,I])
print(r([t1,t2],[pr(I),pr(I)]),'want ambiguous')
