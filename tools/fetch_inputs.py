#!/usr/bin/env python3
"""Download pinned implementation sources, sanitize them, update the manifest.

Sources are listed in tools/inputs.json. Each entry is downloaded to
inputs/raw/<id>/<basename>, sanitized into inputs/clean/<id>/<basename>,
and recorded in inputs/MANIFEST.md. Writers read only inputs/clean/.

Usage:
    tools/fetch_inputs.py [ID ...]     # default: all entries
"""

import hashlib
import json
import subprocess
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONFIG = ROOT / "tools" / "inputs.json"
RAW = ROOT / "inputs" / "raw"
CLEAN = ROOT / "inputs" / "clean"
MANIFEST = ROOT / "inputs" / "MANIFEST.md"


def raw_url(repo: str, ref: str, path: str) -> str:
    return f"https://raw.githubusercontent.com/{repo}/{ref}/{path}"


def main() -> int:
    config = json.loads(CONFIG.read_text())
    wanted = set(sys.argv[1:])
    for entry in config["inputs"]:
        if wanted and entry["id"] not in wanted:
            continue
        repo = config["repos"][entry["repo"]]
        name = Path(entry["path"]).name
        raw = RAW / entry["id"] / name
        clean = CLEAN / entry["id"] / name
        raw.parent.mkdir(parents=True, exist_ok=True)
        clean.parent.mkdir(parents=True, exist_ok=True)
        if not raw.exists():
            url = raw_url(repo["github"], repo["ref"], entry["path"])
            print(f"fetch {url}")
            urllib.request.urlretrieve(url, raw)
        subprocess.run(
            [sys.executable, "-I", str(ROOT / "tools" / "sanitize.py"), str(raw), str(clean)],
            check=True,
        )

    lines = [
        "# Input manifest",
        "",
        "Generated by `tools/fetch_inputs.py`. Raw files are in `inputs/raw/` and",
        "sanitized copies in `inputs/clean/`. Neither directory is tracked.",
        "",
        "## Repositories",
        "",
        "| Key | Repository | Ref | License |",
        "|---|---|---|---|",
    ]
    for key, repo in config["repos"].items():
        lines.append(f"| {key} | {repo['github']} | `{repo['ref']}` | {repo['license']} |")
    lines += [
        "",
        "## Files",
        "",
        "| ID | Repo | Path | Class | SHA-256 (raw) |",
        "|---|---|---|---|---|",
    ]
    for entry in config["inputs"]:
        raw = RAW / entry["id"] / Path(entry["path"]).name
        digest = hashlib.sha256(raw.read_bytes()).hexdigest() if raw.exists() else "(not fetched)"
        lines.append(
            f"| {entry['id']} | {entry['repo']} | `{entry['path']}` | {entry['class']} | `{digest}` |"
        )
    MANIFEST.write_text("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
